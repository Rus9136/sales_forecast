import type { ReactNode } from 'react'

/**
 * Термин со встроенным глоссарием: пунктирное подчёркивание + тултип при наведении.
 * Используется для GP, эластичности, hit-rate и т.п. — термин остаётся на экране,
 * объяснение простыми словами живёт во втором слое.
 */
export function Term({ tip, children }: { tip: string; children: ReactNode }) {
  return (
    <span className="term" data-tip={tip} tabIndex={0}>
      {children}
    </span>
  )
}

